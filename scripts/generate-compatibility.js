#!/usr/bin/env node

/**
 * Generate COMPATIBILITY.md from versions.json
 * Creates compatibility matrix and version information
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function getVersionsData() {
  const versionsPath = path.join(process.cwd(), 'versions.json');
  if (!fs.existsSync(versionsPath)) {
    console.error('❌ versions.json not found');
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(versionsPath, 'utf8'));
}

function generateCompatibilityDoc(versions) {
  const updateDate = new Date(versions.last_updated).toLocaleDateString('en-US');

  let markdown = `# Service Compatibility Matrix

> Last updated: ${updateDate}

## Current Version Compatibility

All services listed below are tested and confirmed to work together:

| Service | Version | Status |
| --- | --- | --- |
`;

  for (const service of versions.services) {
    const status = service.latest_release.prerelease ? '⚠️ Prerelease' : '✅ Stable';
    markdown += `| ${service.name} | \`${service.latest_release.version}\` | ${status} |\n`;
  }

  markdown += `

## Version Combinations

### Latest (Development)

\`\`\`
ThreeTwo: ${versions.services[0]?.latest_release.version}
Metadata Service: ${versions.services[1]?.latest_release.version}
Core Service: ${versions.services[2]?.latest_release.version}
Docker Compose: ${versions.services[3]?.latest_release.version}
\`\`\`

**Status**: ${versions.services.some(s => s.latest_release.prerelease) ? '⚠️ Contains prerelease versions' : '✅ All stable'}

**Used for**: Development and testing

## Deployment Guide

### Production Deployment

For production environments, use stable (non-prerelease) versions:

\`\`\`bash
export THREETWO_VERSION="${versions.services[0]?.latest_release.version}"
export METADATA_SERVICE_VERSION="${versions.services[1]?.latest_release.version}"
export CORE_SERVICE_VERSION="${versions.services[2]?.latest_release.version}"

docker-compose -f docker-compose.yml up -d
\`\`\`

### Development Deployment

For development and testing, latest versions can be used:

\`\`\`bash
git clone https://github.com/rishighan/threetwo.git
cd threetwo
docker-compose up -d --build
\`\`\`

## Known Issues

_Check individual service repositories for current issues:_

${versions.services.map(s => `- [${s.name}](${s.repo}/issues)`).join('\n')}

## Breaking Changes

### v0.0.1

- Initial release
- Core functionality established

### Future Releases

Check the [Release Notes](./VERSIONING_GUIDE.md) for upcoming breaking changes.

## Version Support Policy

- **Latest**: Always supported, may include breaking changes
- **Stable releases**: Supported for 6+ months
- **End of life**: Check individual repositories

## Upgrade Path

When upgrading between versions:

1. **Backup your data**
   \`\`\`bash
   docker-compose down -v  # Be careful!
   \`\`\`

2. **Update service versions** in docker-compose.yml

3. **Restart services**
   \`\`\`bash
   docker-compose up -d --build
   \`\`\`

4. **Verify functionality**
   \`\`\`bash
   docker-compose logs -f
   \`\`\`

## Checking Version Compatibility

To ensure all services are compatible:

\`\`\`bash
# Check all running container versions
docker ps --format "table {{.Names}}\\t{{.Image}}" | grep -E "(threetwo|metadata|core)"

# Compare against versions.json
cat versions.json
\`\`\`

## Support

For compatibility questions or issues:

${versions.services.map(s => `- **${s.name}**: [${s.repo}](https://github.com/${s.repo})`).join('\n')}

---

**Last Updated**: ${updateDate}
**Auto-generated by**: [Version Update Workflow](.github/workflows/auto-update-versions.yml)
`;

  return markdown;
}

function generateCompatibility() {
  console.log('📋 Generating COMPATIBILITY.md...\n');

  const versions = getVersionsData();
  const markdown = generateCompatibilityDoc(versions);

  const compatPath = path.join(process.cwd(), 'COMPATIBILITY.md');
  fs.writeFileSync(compatPath, markdown + '\n');

  console.log('   ✅ Generated COMPATIBILITY.md');
  console.log('\n✅ Generated compatibility documentation');
}

generateCompatibility().catch((error) => {
  console.error('❌ Error generating compatibility doc:', error);
  process.exit(1);
});

